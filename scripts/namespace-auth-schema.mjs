import { readFile, writeFile } from "node:fs/promises"

const schemaPath = new URL("../src/server/db/auth-schema.ts", import.meta.url)
const generated = await readFile(schemaPath, "utf8")

if (!generated.includes('pgTable("user"')) {
  throw new Error(
    "The generated Better Auth schema does not have the expected Drizzle structure."
  )
}

const namespaced = generated
  .replace("  pgTable,\n", "  pgSchema,\n")
  .replace(
    'export const user = pgTable("user",',
    'export const betterAuthSchema = pgSchema("better_auth")\n\nexport const user = betterAuthSchema.table("user",'
  )
  .replaceAll("pgTable(", "betterAuthSchema.table(")

await writeFile(
  schemaPath,
  `// Generated by the Better Auth CLI; mapped to the reserved PostgreSQL schema\n// better_auth via scripts/namespace-auth-schema.mjs.\n${namespaced}`
)
